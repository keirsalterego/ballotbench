"""The normalization proof: everything JUDGING.md claims about calibration,
recomputed from the database's scores. Deterministic, so the output in the
docs can be regenerated byte for byte:

    docker compose exec web python manage.py normalization_proof
"""
import math
import random
from collections import defaultdict

from django.core.management.base import BaseCommand

from portal import pairwise
from portal.calibration import bootstrap, fit, kingmakers, signal_test
from portal.models import Event, Membership
from portal.results import submitted_reviews
from portal.scoring import weighted_score


def kendall(a, b):
    pos = {x: i for i, x in enumerate(b)}
    agree = total = 0
    for i in range(len(a)):
        for k in range(i + 1, len(a)):
            total += 1
            agree += pos[a[i]] < pos[a[k]]
    return 2 * agree / total - 1 if total else 1.0


def zscore_order(obs):
    """The usual alternative: standardize each judge, then average."""
    by_j = defaultdict(list)
    for j, p, y in obs:
        by_j[j].append(y)
    stats = {}
    for j, ys in by_j.items():
        m = sum(ys) / len(ys)
        sd = math.sqrt(sum((y - m) ** 2 for y in ys) / len(ys))
        stats[j] = (m, sd)
    by_p = defaultdict(list)
    for j, p, y in obs:
        m, sd = stats[j]
        by_p[p].append((y - m) / sd if sd > 0 else 0.0)
    return sorted(by_p, key=lambda p: -sum(by_p[p]) / len(by_p[p]))


def synthetic(seed, n_projects=40, n_judges=12, k=3):
    rng = random.Random(seed)
    truth = {p: rng.gauss(0, 1) for p in range(n_projects)}
    judges = {j: (rng.uniform(-0.15, 0.15), rng.uniform(0.05, 0.2), rng.uniform(0.02, 0.08)) for j in range(n_judges)}
    ranked = sorted(truth, key=truth.get, reverse=True)
    obs = []
    for p in range(n_projects):
        chosen = rng.sample(range(1, n_judges), k)
        if p in ranked[:8]:
            chosen[0] = 0
        for j in chosen:
            a, s, v = judges[j]
            obs.append((j, p, 0.5 + a - (0.25 if j == 0 else 0) + s * truth[p] + rng.gauss(0, v)))
    return obs, ranked


class Command(BaseCommand):
    help = "Recompute the calibration claims in JUDGING.md from the fixture event's scores."

    def add_arguments(self, parser):
        parser.add_argument("--event", default="sample-hack-2026")

    def handle(self, *args, event, **options):
        ev = Event.objects.get(slug=event)
        criteria = list(ev.criteria.all())
        names, titles = {}, {}
        obs = []
        for r in submitted_reviews(ev):
            y = weighted_score(r, criteria)
            if y is None:
                continue
            a = r.assignment
            obs.append((a.judge_id, a.project_id, y))
            titles[a.project_id] = (a.project.external_id or str(a.project_id), a.project.title)
        for m in Membership.objects.filter(event=ev, role="judge").select_related("user"):
            names[m.user_id] = m.external_id or m.user.email
        out = self.stdout.write

        if not obs:
            out(f"Normalization proof: {ev.name} has no submitted reviews yet, so there is nothing to calibrate.")
            return
        result = fit(obs)
        out(f"Normalization proof: {ev.name}, {len(obs)} reviews, {len(result.judges)} judges, "
            f"{len(result.projects)} projects")
        out(f"Model: y = a_j + s_j*q_i + e, fitted in {result.iterations} iterations "
            f"({'converged' if result.converged else 'NOT converged'}), judge-project graph in "
            f"{result.components} component(s).\n")

        flagged = sorted((jf.flag, names.get(j, j), jf.n) for j, jf in result.judges.items() if jf.flag != "ok")
        out("Judges carrying no weight (s_j = 0):")
        for flag, name, n in flagged:
            out(f"  {name:<8} {n:>2} review(s)  {flag}")
        out(f"  the other {len(result.judges) - len(flagged)} judges: ok\n")

        observed, shuffled, p = signal_test(obs, shuffles=2000, seed=1)
        out(f"Agreement: variance of project means {observed:.4f}, {shuffled:.4f} on average when every score is "
            f"shuffled across the same slots (permutation p = {p:.3f}, 2000 shuffles).")
        if p >= 0.05:
            out("  The judges agree on which projects are better no more than chance would. Calibration takes out\n"
                "  judge habits; it can't create a signal the scores don't hold, so most rank moves below are noise.\n")
        else:
            out("  The judges agree far more than chance would: there is a real signal to calibrate.\n")

        # Rank what the product ranks: flagged duplicates stay out, though
        # their reviews still inform the judges' calibration.
        dupes = {p.pk: p for p in ev.projects.filter(duplicate_of__isnull=False).select_related("duplicate_of")}
        for pid, p in dupes.items():
            out(f"Left out of the ranking: {p.external_id} ({p.title}) repeats {p.duplicate_of.external_id}; "
                f"its {result.projects[pid].n} reviews still count towards calibrating their judges.")
        # ...and, like the calibration page, projects whose every reviewer the
        # model ignores: there's nothing to rank them by.
        unusable = sorted((p for p in result.projects if p not in dupes and result.projects[p].usable == 0), key=str)
        for pid in unusable:
            out(f"Left out of the ranking: {titles[pid][0]} ({titles[pid][1]}): all {result.projects[pid].n} of its "
                f"reviewers carry no weight, so there's nothing to rank it by.")
        ranked = [p for p in result.projects if p not in dupes and p not in unusable]
        raw_order = sorted(ranked, key=lambda p: (-result.projects[p].raw_mean, p))
        cal_order = sorted(ranked, key=lambda p: (-result.projects[p].quality, -result.projects[p].raw_mean, p))
        raw_rank = {p: i + 1 for i, p in enumerate(raw_order)}
        intervals = bootstrap(obs, rankable=set(ranked))
        out(f"{'rank':>4} {'could be':>9} {'raw':>4} {'move':>5}  {'project':<8} {'title':<16} {'n':>2} "
            f"{'raw mean':>8} {'calibrated':>10}")
        for i, pid in enumerate(cal_order, 1):
            pf = result.projects[pid]
            move = raw_rank[pid] - i
            ext, title = titles[pid]
            low, high, _ = intervals[pid]
            out(f"{i:>4} {f'{low}-{high}':>9} {raw_rank[pid]:>4} {('+' if move > 0 else '') + str(move) if move else '':>5}"
                f"  {ext:<8} {title[:16]:<16} {pf.n:>2} {pf.raw_mean:>8.3f} {result.display(pid):>10.3f}")
        moved = sum(1 for i, pid in enumerate(cal_order, 1) if raw_rank[pid] != i)
        widths = sorted(high - low for low, high, _ in intervals.values())
        out(f"\n{moved} of {len(cal_order)} projects change rank. Kendall's tau, calibrated vs raw: "
            f"{kendall(cal_order, raw_order):.3f}")
        out(f"'could be' is a 90% bootstrap interval (each project's reviews resampled, 200 refits). Median width "
            f"{widths[len(widths) // 2]} places: on these scores most ranks are not distinguishable.\n")

        out("Invariance checks on these scores (max |change in q| over all projects):")
        busiest = max(result.judges, key=lambda j: (result.judges[j].n, str(names.get(j))))
        constant = [j for j, jf in result.judges.items() if jf.flag == "constant"]
        checks = [
            (f"{names.get(busiest)} adds 0.3 to every score", [(j, p, y + 0.3 if j == busiest else y) for j, p, y in obs]),
            (f"{names.get(busiest)} doubles every score", [(j, p, 2 * y if j == busiest else y) for j, p, y in obs]),
            ("every judge gets a random shift and stretch",
             self.every_judge_moved(obs)),
            (f"constant judge(s) {', '.join(str(names.get(j)) for j in constant) or 'none'} removed",
             [o for o in obs if o[0] not in constant]),
        ]
        ok = True
        for label, moved_obs in checks:
            other = fit(moved_obs)
            diff = max(abs(result.projects[p].quality - other.projects[p].quality) for p in other.projects)
            same = [p for p in cal_order if p in other.projects] == sorted(
                (p for p in other.projects if p in cal_order),
                key=lambda p: (-other.projects[p].quality, -result.projects[p].raw_mean, p))
            passed = diff < 1e-9 and same
            ok &= passed
            out(f"  {'PASS' if passed else 'FAIL'}  {label}: {diff:.1e}, ranking {'identical' if same else 'CHANGED'}")

        decisive = kingmakers(obs, set(ranked), podium=3)
        out(f"\nKingmaker check: leaving out one judge at a time, {len(decisive)} of {len(result.judges)} judges' "
            f"absence would change who is in the top 3:")
        for j, entered, left in decisive:
            out(f"  without {names.get(j)}: {', '.join(titles[p][0] for p in entered)} in, "
                f"{', '.join(titles[p][0] for p in left)} out")

        out("\nSecond opinion: the rubric read as pairwise picks (Bradley-Terry, portal/pairwise.py):")
        pairs = pairwise.picks(obs)
        silent = sorted(str(names.get(j)) for j, jf in result.judges.items() if jf.n < 2 or jf.flag == "constant")
        strengths = pairwise.fit(pairs, items=ranked)
        bt_order = sorted(ranked, key=lambda p: (-strengths[p], p))
        out(f"  {len(pairs)} picks; no picks from {', '.join(silent)} (one review, or every pair tied)")
        out(f"  Kendall's tau with the calibrated ranking {pairwise.kendall(bt_order, cal_order):.3f}, "
            f"with raw means {pairwise.kendall(bt_order, raw_order):.3f}")
        squashed = [(j, p, y ** 2 if j == busiest else y) for j, p, y in obs]
        same_picks = sorted(pairwise.picks(squashed)) == sorted(pairs)
        moved_q = max(abs(result.projects[p].quality - fit(squashed).projects[p].quality) for p in ranked)
        ok &= same_picks
        out(f"  {'PASS' if same_picks else 'FAIL'}  {names.get(busiest)}'s scores squared (not a shift or stretch): "
            f"picks identical; the calibration's q moves by up to {moved_q:.2f}, since it only undoes linear habits")

        out("\nBenchmark on synthetic events with a known true order (40 projects, 12 judges, 3 reviews each,")
        out("one harsh judge who only sees the strongest projects). Kendall's tau against the truth:")
        rows = []
        for seed in range(20):
            s_obs, truth = synthetic(seed)
            s_fit = fit(s_obs)
            model = sorted(s_fit.projects, key=lambda p: -s_fit.projects[p].quality)
            raw = sorted(s_fit.projects, key=lambda p: -s_fit.projects[p].raw_mean)
            bt = pairwise.fit(pairwise.picks(s_obs), items=list(s_fit.projects))
            bt_order = sorted(bt, key=lambda p: (-bt[p], p))
            rows.append((kendall(model, truth), kendall(raw, truth), kendall(zscore_order(s_obs), truth),
                         kendall(bt_order, truth)))
        avg = [sum(r[i] for r in rows) / len(rows) for i in range(4)]
        out(f"  calibration {avg[0]:.3f}   raw means {avg[1]:.3f}   per-judge z-scores {avg[2]:.3f}   "
            f"pairwise picks {avg[3]:.3f}   (mean of 20 events)")
        out(f"  calibration beats raw means in {sum(r[0] > r[1] for r in rows)} of 20, "
            f"z-scores in {sum(r[0] > r[2] for r in rows)} of 20\n")
        out("Every invariance check holds." if ok else "SOME INVARIANCE CHECK FAILED.")
        if not ok:
            raise SystemExit(1)

    def every_judge_moved(self, obs):
        rng = random.Random(3)
        moves = {}
        for j, _, _ in obs:
            moves.setdefault(j, (rng.uniform(-2, 2), rng.uniform(0.2, 5)))
        return [(j, p, moves[j][0] + moves[j][1] * y) for j, p, y in obs]
